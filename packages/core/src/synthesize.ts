import { AgentName, TheseusConfig, formatZodIssues } from "./config.js";
import { catalogTargets } from "./catalog.js";
import { TheseusError } from "./errors.js";

/** Everything `theseus regrow <url>` and `theseus init <url>` take on the command line. */
export interface RegrowRequest {
  readonly url: string;
  /** Stack preset ids from the catalog. */
  readonly to: readonly string[];
  /** The builder agent for every target; mutually exclusive with `race`. */
  readonly agent?: AgentName;
  /** Two or more agents: each stack is regrown once per agent. */
  readonly race?: readonly AgentName[];
  /** Documentation files for the drafting agent, written into the config as given. */
  readonly docs?: readonly string[];
  /** Voyage id; derived from the URL when absent. */
  readonly name?: string;
  readonly budget?: number;
  readonly rounds?: number;
}

const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

export function slugify(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function parseUrl(raw: string): URL {
  let url: URL;
  try {
    url = new URL(raw);
  } catch (error) {
    throw new TheseusError("config-invalid", `"${raw}" is not a URL; pass the running original, e.g. http://localhost:4170`, { cause: error });
  }
  if (url.protocol !== "http:" && url.protocol !== "https:") {
    throw new TheseusError("config-invalid", `"${raw}" must be an http or https URL`);
  }
  return url;
}

/** `http://localhost:4170` becomes `localhost-4170`; `https://todo.example.com/app` becomes `todo-example-com-app`. */
export function voyageIdFor(url: URL): string {
  const parts = [url.hostname, url.port, url.pathname].filter((part) => part.length > 0 && part !== "/");
  const id = slugify(parts.join("-"));
  return id.length > 0 ? id : "app";
}

function agentsOf(request: RegrowRequest): AgentName[] {
  if (request.race !== undefined && request.agent !== undefined) {
    throw new TheseusError("config-invalid", "use --agent or --race, not both");
  }
  if (request.race === undefined) return [request.agent ?? "claude-code"];
  const agents = [...new Set(request.race)];
  if (agents.length < 2) {
    throw new TheseusError("config-invalid", `a race needs two different agents, e.g. --race ${AgentName.options.join(",")}`);
  }
  return agents;
}

/**
 * Builds a complete, validated Theseus config from command-line flags, with every default written
 * out so the result doubles as an editable starting point for `theseus voyage`.
 */
export function synthesizeConfig(request: RegrowRequest): TheseusConfig {
  const url = parseUrl(request.url);
  const id = request.name === undefined ? voyageIdFor(url) : request.name;
  if (!SLUG.test(id)) throw new TheseusError("config-invalid", `--name "${id}" must be kebab-case, e.g. ${slugify(id) || "my-app"}`);
  const docs = request.docs ?? [];
  const raw = {
    id,
    title: `${url.host}, regrown`,
    app: {
      name: url.host,
      description: `The app served at ${url.href}. Its behaviors are captured from the running app${docs.length > 0 ? " and its docs" : ""}.`,
    },
    original: { label: "Original", stack: "the running original (stack not declared)", url: url.href },
    docs: [...docs],
    targets: catalogTargets(request.to, agentsOf(request)),
    ...(request.rounds === undefined ? {} : { rounds: request.rounds }),
    ...(request.budget === undefined ? {} : { budgetCredits: request.budget }),
    draftAgent: { agent: request.race?.[0] ?? request.agent ?? "claude-code" },
  };
  const parsed = TheseusConfig.safeParse(raw);
  if (!parsed.success) throw new TheseusError("config-invalid", `the flags do not make a valid config:\n${formatZodIssues(parsed.error)}`);
  return parsed.data;
}

/**
 * The config as an annotated JSON document. JSON has no comments, so the notes live under `//`
 * keys, which the config schema ignores.
 */
export function renderConfigJson(config: TheseusConfig, command: string): string {
  const annotated = {
    "//": [
      `Generated by: ${command}`,
      "Run it with: theseus voyage <this file>. Every phase resumes where it stopped.",
      "original.url must be running while capture and baseline run. Add original.source to enable the strength phase.",
      "targets[].agent is claude-code or codex; two targets with the same stack and different agents race each other.",
      "budgetCredits caps Kane credits for the whole voyage; kane.creditsPerRun is the estimate the budget guard uses.",
    ],
    ...config,
  };
  return `${JSON.stringify(annotated, null, 2)}\n`;
}
